import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createApi } from '../lib/api.js';
import { Engine } from '../engine.js';

test('Next.js API handler: session roles, gate boundary, persistence and export', async t => {
  const engine = new Engine();
  const handle = createApi(engine);
  t.after(() => engine.close());
  const base = 'http://127.0.0.1:3000';
  const fetch = (url, init) => handle(new Request(url, init));
  const first = await fetch(`${base}/api/state`);
  const cookie = first.headers.get('set-cookie').split(';')[0];
  const initial = await first.json();
  const post = (path, body, extra = {}) => fetch(`${base}/api/${path}`, { method: 'POST', headers: { Cookie: cookie, 'Content-Type': 'application/json', 'X-CSRF-Token': initial.csrf, ...extra }, body: JSON.stringify(body) });
  assert.equal((await fetch(`${base}/api/run`, { method: 'POST' })).status, 401);
  assert.equal((await post('run', { scenario: 'safe' }, { 'X-CSRF-Token': 'bad' })).status, 403);
  assert.equal((await post('run', { scenario: 'safe' }, { Origin: 'https://other.example' })).status, 403);
  assert.equal((await post('create_payment_request', {})).status, 404);
  assert.equal((await post('run', { scenario: 'unknown' })).status, 400);
  assert.equal((await post('session', { role: '__proto__' })).status, 400);
  assert.equal((await post('run', { scenario: 'safe', padding: 'a'.repeat(9000) })).status, 413);
  const blocked = await (await post('run', { scenario: 'bank' })).json();
  assert.equal(blocked.result.toolInvocations, 0);
  const pending = await (await post('run', { scenario: 'review' })).json();
  const id = pending.result.id;
  assert.equal((await post('approve', { id, role: 'finance', approver: 'finance-reviewer' })).status, 403);
  assert.equal((await post('session', { role: 'finance' })).status, 200);
  assert.equal((await post('approve', { id })).status, 200);
  const executed = await (await post('execute', { id })).json();
  assert.equal(executed.result.status, 'VERIFIED');
  assert.equal(executed.result.toolInvocations, 1);
  const exported = await fetch(`${base}/api/export`, { headers: { Cookie: cookie } });
  assert.match(exported.headers.get('content-disposition'), /chainguard-audit.json/);
  const evidence = await exported.json();
  assert.equal(evidence.simulation, true);
  assert.equal(evidence.metrics.requests, 1);
  assert.ok(evidence.events.some(e => e.kind === 'APPROVAL_REJECTED'));
  assert.equal((await post('reset', {})).status, 200);
  assert.equal(engine.snapshot().metrics.transactions, 0);
});
